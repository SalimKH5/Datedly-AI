const DICTS: Record<Lang, Record<Key, string>> = { en, fr };
const STORAGE_KEY = "datedly.lang";
const listeners = new Set<() => void>();

function read(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "en" || v === "fr") return v;
  } catch {
    /* storage blocked: fall back to the browser language */
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  window.addEventListener("storage", cb);
  return () => {
    listeners.delete(cb);
    window.removeEventListener("storage", cb);
  };
}

export function setLang(lang: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* not persisted, still applied for this page */
  }
  memo = lang;
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

let memo: Lang | null = null;
const getSnapshot = () => (memo ??= read());
const getServerSnapshot = (): Lang => "en";

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT(): { t: T; lang: Lang; locale: string } {
  const lang = useLang();
  const t = useCallback<T>((key, vars) => translate(lang, key, vars), [lang]);
  return { t, lang, locale: lang === "fr" ? "fr-FR" : "en-US" };
}

/** Labels shown inside a calendar follow the calendar's own language. */
export function contentLang(calendarLang: string, ui: Lang): Lang {
  const l = calendarLang.toLowerCase().slice(0, 2);
  return l === "fr" || l === "en" ? l : ui;
}
